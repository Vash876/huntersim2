/**
 * Hilfsfunktion, die prüft, ob zwei Trait Spheres benachbart sind
 */
export function areTraitSpheresNeighbors(id1, id2) {
  return traitSphereNeighbors[id1]?.includes(id2) || traitSphereNeighbors[id2]?.includes(id1);
}

/**
 * Prüft, ob eine Trait Sphere zu mindestens einer ausgewählten Trait Sphere benachbart ist
 */
export function isAdjacentToAnySelected(sphereId, selectedSpheres) {
  return selectedSpheres.some(selectedId => areTraitSpheresNeighbors(sphereId, selectedId));
}
