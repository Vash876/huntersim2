/**
 * Hilfsfunktion zum Abrufen einer Trait Sphere anhand der ID
 */
export function getTraitSphereById(id) {
  return traitSpheres.find(sphere => sphere.id === id);
}

/**
 * Hilfsfunktion zum Abrufen aller Trait Spheres an einer bestimmten Position
 */
export function getTraitSphereAtPosition(col, row) {
  return traitSpheres.find(sphere => sphere.col === col && sphere.row === row);
}

/**
 * Gibt das gesamte Grid als 2D-Array zurück
 * Nützlich zum direkten Rendern des Grids
 */
export function getTraitSphereGrid() {
  const grid = Array(6).fill().map(() => Array(7).fill(null));
  
  traitSpheres.forEach(sphere => {
    if (sphere.col >= 0 && sphere.row >= 0) {
      grid[sphere.row][sphere.col] = sphere;
    }
  });
  
  return grid;
}

