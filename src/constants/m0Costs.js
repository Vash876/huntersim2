// Hilfsfunktion um M0 Kosten für ein bestimmtes Level zu erhalten
export function getM0Cost(level) {
  return M0_COSTS[level] || 0;
}

// Hilfsfunktion um die Gesamtkosten von Level 1 bis zum Ziellevel zu berechnen
export function getTotalM0Cost(targetLevel) {
  let totalCost = 0;
  for (let level = 1; level <= targetLevel; level++) {
    totalCost += getM0Cost(level);
  }
  return totalCost;
}
